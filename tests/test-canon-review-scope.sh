#!/usr/bin/env bash
# 1.9.2 회귀 — **외부 리뷰는 도메인을 가리지 않는다**.
# 왜 문구 테스트인가: 외부 리뷰 스킬을 만들지 말지는 **모델이 정본을 읽고 판단**한다.
# 즉 계약은 스크립트가 아니라 SKILL.md 문장에 있다. 그 문장이 되돌아가면 생성 하네스에서
# 게이트가 조용히 꺼진다(실측: 1.9.1 로 만든 리서치·웹툰 하네스 둘 다 external-review-loop 가 없었다).
set -uo pipefail
S="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/skills/myharness/SKILL.md"
pass=0; fail=0
ok(){ printf '  ✓ %s\n' "$1"; pass=$((pass+1)); }
no(){ printf '  ✗ FAIL: %s\n' "$1"; fail=$((fail+1)); }
has(){ grep -qF -- "$1" "$S"; }

printf '\n== 1.9.2 외부 리뷰 적용 범위 ==\n'
has '품질 게이트 2층 (도메인 무관).' && ok "원칙이 도메인 무관으로 적혀 있다" || no "원칙 제목이 도메인 한정으로 되돌아갔다"
has '도메인으로 켜고 끄지 않는다' && ok "조건이 '리뷰어 유무 + 반출 정책' 둘로 명시됐다" || no "켜고 끄는 조건 문장이 사라졌다"
has '4-6. 외부 리뷰 스킬 생성 (도메인 무관' && ok "4-6 제목이 도메인 무관이다" || no "4-6 제목이 코드/설계로 되돌아갔다"
has '5-6. 품질 게이트 (도메인 무관)' && ok "5-6 제목이 도메인 무관이다" || no "5-6 제목이 코드/설계로 되돌아갔다"

printf '\n== 되돌아가면 안 되는 문구 ==\n'
for bad in '비코드 도메인은 점검 없이 생략' '품질 게이트 2층 (코드/설계 도메인)' '4-6. 외부 리뷰 스킬 생성 (코드/설계' '5-6. 품질 게이트 (코드/설계 도메인)'; do
  has "$bad" && no "도메인 제약 문구가 남아 있다: $bad" || ok "제거됨: $bad"
done
grep -q '^| 단순/비코드 · 코드 경량 .*외부 리뷰' "$S" && no "패턴표가 비코드에서 외부 리뷰를 다시 제외한다" || ok "패턴표 행 구분이 리스크 등급이다"

printf '\n== 반출 기본값 드리프트 차단 ==\n'
has '임의로 더 좁은 값을 **선언(`declared`)하지 않는다**' && ok "'추천값으로' 요청 시 --defaults 를 쓰도록 못박혀 있다" || no "기본값 드리프트 차단 문장이 없다"
has 'runtime-only` 로 스스로 고르면' && ok "runtime-only 자가 선택의 결과(외부 리뷰 꺼짐)가 적혀 있다" || no "그 사유 문장이 없다"

printf '\n통과 %d · 실패 %d\n' "$pass" "$fail"
[ "$fail" = 0 ]
